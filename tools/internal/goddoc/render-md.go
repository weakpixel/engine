package goddoc

import (
	"fmt"
	"strconv"
	"strings"
	"unicode"

	"github.com/weakpixel/engine/god"
)

// mdFile is one Markdown output file: its name ("" for the single-file
// output) and the function that writes its content.
type mdFile struct {
	name   string
	render func(w *mdWriter)
}

// mdLoc is where a heading ended up: the file and its GitHub anchor.
type mdLoc struct {
	file, slug string
}

// mdSite renders a set of Markdown files that link to each other. Anchors are
// derived from the heading text by slug, so links must know every heading
// before any file is final. renderFiles therefore renders everything twice: the
// first pass only records where each heading lands, the second pass writes
// links that resolve.
type mdSite struct {
	loc map[any]mdLoc // heading ref -> location
}

// mdWriter writes one Markdown file.
type mdWriter struct {
	site  *mdSite
	file  string
	slugs map[string]int // slug -> times used, for GitHub's -1, -2 suffixes
	b     strings.Builder
}

// renderFiles returns the content of each file by name.
func renderFiles(files []mdFile) map[string]string {
	site := &mdSite{loc: map[any]mdLoc{}}
	out := map[string]string{}
	for pass := range 2 {
		for _, f := range files {
			w := &mdWriter{site: site, file: f.name, slugs: map[string]int{}}
			f.render(w)
			if pass == 1 {
				out[f.name] = w.b.String()
			}
		}
	}
	return out
}

// slug is GitHub's heading anchor: lower case, spaces to hyphens, everything
// but letters, digits, hyphens and underscores removed.
func slug(heading string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(heading) {
		switch {
		case r == ' ':
			b.WriteByte('-')
		case r == '-' || r == '_' || unicode.IsLetter(r) || unicode.IsDigit(r):
			b.WriteRune(r)
		}
	}
	return b.String()
}

// heading writes a heading and records its anchor under ref (nil: unlinked).
// A repeated slug gets GitHub's numeric suffix.
func (w *mdWriter) heading(level int, text string, ref any) {
	s := slug(text)
	n := w.slugs[s]
	w.slugs[s]++
	if n > 0 {
		s += "-" + strconv.Itoa(n)
	}
	if ref != nil {
		w.site.loc[ref] = mdLoc{file: w.file, slug: s}
	}
	w.b.WriteString(strings.Repeat("#", level) + " " + text + "\n\n")
}

// link returns a Markdown link to the heading registered under ref.
func (w *mdWriter) link(text string, ref any) string {
	loc := w.site.loc[ref]
	target := "#" + loc.slug
	if loc.file != w.file {
		target = loc.file + target
	}
	return "[" + text + "](" + target + ")"
}

func (w *mdWriter) para(text string) {
	if text != "" {
		w.b.WriteString(text + "\n\n")
	}
}

func (w *mdWriter) line(text string) { w.b.WriteString(text + "\n") }

// table writes a GFM table; every cell is escaped.
func (w *mdWriter) table(header []string, rows [][]string) {
	w.line("| " + strings.Join(header, " | ") + " |")
	w.line("|" + strings.Repeat(" --- |", len(header)))
	for _, row := range rows {
		cells := make([]string, len(row))
		for i, c := range row {
			cells[i] = cell(c)
		}
		w.line("| " + strings.Join(cells, " | ") + " |")
	}
	w.b.WriteString("\n")
}

// cell makes text safe for a table cell: runs of whitespace (including
// newlines, which would end the row) become one space and "|" is escaped.
// Links are generated by the caller and contain no pipes.
func cell(text string) string {
	return strings.ReplaceAll(strings.Join(strings.Fields(text), " "), "|", `\|`)
}

// withValues appends the enum members of a field to its description:
// "Values: `0 KindPoint`: doc; `1 KindCircle`."
func withValues(desc string, values []god.EnumValue) string {
	if len(values) == 0 {
		return desc
	}
	items := make([]string, len(values))
	for i, v := range values {
		items[i] = fmt.Sprintf("`%d %s`", v.Value, v.Name)
		if v.Doc != "" {
			items[i] += ": " + strings.TrimSuffix(v.Doc, ".")
		}
	}
	return strings.TrimSpace(desc + " Values: " + strings.Join(items, "; ") + ".")
}

// withDefault appends the initial value of a field to its description.
func withDefault(desc, def string) string {
	if def == "" {
		return desc
	}
	return strings.TrimSpace(desc + " Default: `" + def + "`.")
}

// embeddedLabel is "embedded (Common.Base)", or "" for a direct component.
func embeddedLabel(via []string) string {
	if len(via) == 0 {
		return ""
	}
	return "embedded (" + strings.Join(via, ".") + ")"
}

func yes(b bool) string {
	if b {
		return "yes"
	}
	return ""
}

// flags lists the words describing how an object uses a component.
func (c objectComponent) flags() string {
	var f []string
	if c.Optional {
		f = append(f, "optional")
	}
	if c.Readonly {
		f = append(f, "readonly")
	}
	if e := embeddedLabel(c.Via); e != "" {
		f = append(f, e)
	}
	return strings.Join(f, ", ")
}

// renderMarkdown renders doc as one file, returned under the name "".
func renderMarkdown(doc *document) string {
	return renderFiles([]mdFile{{name: "", render: func(w *mdWriter) {
		w.heading(1, doc.Title, nil)
		w.heading(2, "Contents", nil)
		mdContents(w, doc)
		w.heading(2, "Objects", nil)
		for _, g := range doc.Groups {
			for _, o := range g.Objects {
				mdObject(w, o, 3)
			}
		}
		w.heading(2, "Components", nil)
		for _, c := range doc.Components {
			mdComponent(w, c, 3)
		}
	}}})[""]
}

// splitFiles is the name of the index and the component file in split output.
const (
	splitIndex      = "index.md"
	splitComponents = "components.md"
)

// groupFileName is the file holding the objects of a group in split output.
func groupFileName(group string) string { return "group-" + group + ".md" }

// renderMarkdownSplit renders doc as index.md, components.md and one file per
// group, returned by file name.
func renderMarkdownSplit(doc *document) map[string]string {
	files := []mdFile{
		{splitIndex, func(w *mdWriter) {
			w.heading(1, doc.Title, nil)
			mdContents(w, doc)
		}},
		{splitComponents, func(w *mdWriter) {
			w.heading(1, "Components", nil)
			for _, c := range doc.Components {
				mdComponent(w, c, 2)
			}
		}},
	}
	for _, g := range doc.Groups {
		files = append(files, mdFile{groupFileName(g.Name), func(w *mdWriter) {
			w.heading(1, "Group "+g.Name, nil)
			for _, o := range g.Objects {
				mdObject(w, o, 2)
			}
		}})
	}
	return renderFiles(files)
}

// mdContents writes the two indexes: objects grouped by group, then components.
func mdContents(w *mdWriter, doc *document) {
	w.para("**Objects**")
	for _, g := range doc.Groups {
		w.line("- " + g.Name)
		for _, o := range g.Objects {
			w.line("  - " + w.link(o.Class, o))
		}
	}
	w.line("")
	w.para("**Components**")
	for _, c := range doc.Components {
		w.line("- " + w.link(c.Key, c))
	}
	w.line("")
}

func mdObject(w *mdWriter, o *object, level int) {
	w.heading(level, o.key(), o)
	w.para(o.Doc)
	if len(o.Components) == 0 {
		w.para("_No components._")
		return
	}
	var rows [][]string
	for _, c := range o.Components {
		rows = append(rows, []string{w.link(c.Comp.Key, c.Comp), "`" + c.Field + "`", c.flags(), c.Doc})
	}
	w.table([]string{"Component", "Field", "Flags", "Description"}, rows)
}

func mdComponent(w *mdWriter, c *component, level int) {
	w.heading(level, c.Key, c)
	w.para(c.Doc)
	if c.GoType != "" {
		w.para("Go type: `" + c.GoType + "`")
	}
	if len(c.Rows) == 0 {
		w.para("Type: `" + c.Type + "`")
	} else {
		var rows [][]string
		for _, r := range c.Rows {
			rows = append(rows, []string{"`" + r.Name + "`", "`" + r.Type + "`" + runtimeNote(r), yes(r.Required), yes(r.Nullable), withDefault(withValues(r.Description, r.Values), r.Default)})
		}
		w.table([]string{"Field", "Type", "Required", "Nullable", "Description"}, rows)
	}
	w.para("**Used by**")
	if len(c.Users) == 0 {
		w.para("_No object uses it yet._")
		return
	}
	for _, u := range c.Users {
		item := "- " + w.link(u.Object.key(), u.Object)
		if e := embeddedLabel(u.Via); e != "" {
			item += " — " + e
		}
		w.line(item)
	}
	w.line("")
}

// runtimeNote marks the type cell of a runtime (x-runtime) field.
func runtimeNote(r fieldRow) string {
	if r.Runtime {
		return " *(runtime)*"
	}
	return ""
}
