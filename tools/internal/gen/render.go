const (
	generatedHeader   = "// Code generated by wpix gen; DO NOT EDIT."
	componentIDPrefix = "CID_"
	ecsImportPath     = "github.com/weakpixel/ecs"
	maxTypedArity     = 16
	godGenerator      = "wpix gen"
	godVersion        = 0
)

//go:embed generator.go.tpl
var templatesFS embed.FS

type tplImport struct {
	Name string
	Path string
}

// tplComp is one component of an object as the template sees it.
type tplComp struct {
	Name      string
	Path      string // dotted field chain from the object
	Type      string // qualified component type
	CID       string
	Optional  bool
	ByValue   bool
	Component bool
	Index     int    // position among the object's required components
	Var       string // local variable holding the value to store
	Deref     string // "*" when the object field is a value component
	Expr      string // expression yielding the component pointer while iterating
	SchemaLit string // component types only: JSON layout of the type
	SchemaVar string // local variable in init holding the parsed schema
	Group     string // component identity
	CompName  string
	GoType    string
}

type tplEmbed struct {
	Path string
	Type string
}

type tplObject struct {
	Name       string
	GoType     string // "importpath.Type"
	All        []tplComp
	Required   []tplComp
	Optional   []tplComp
	PtrEmbeds  []tplEmbed
	Typed      bool // 1..maxTypedArity required components: use the typed ecs API
	Count      int
	TypeArgs   string
	IterVar    string // Each/Get loop or result variable: "comp" (typed), "components" (untyped, >16 required), "_" (0 required)
	QueryArgs  string // required CIDs passed to world.Query, untyped case only
	ValueArgs  string // v0, v1, ... in required-component order
	AllCIDArgs string // every component's CID (required+optional), for Remove
	Group      string
	Class      string
	Key        string
	Declared   []tplComp // components in declaration order, for RegisterSchema
}

type tplFile struct {
	ComponentIDPrefix string
	PackageName       string
	Imports           []tplImport
	Components        []tplComp
	Objects           []tplObject
}

// aliases allocates one import alias per package for a generated file.
type aliases struct {
	target string
	byPath map[string]string
	used   map[string]bool
	order  []tplImport
}

func newAliases(target string) *aliases {
	return &aliases{
		target: target,
		byPath: map[string]string{},
		used:   map[string]bool{"ecs": true, "iter": true, "god": true},
	}
}

func (a *aliases) qualify(pkg *types.Package) string {
	if pkg.Path() == a.target {
		return ""
	}
	if alias, ok := a.byPath[pkg.Path()]; ok {
		return alias
	}
	alias := pkg.Name()
	for n := 2; a.used[alias]; n++ {
		alias = pkg.Name() + strconv.Itoa(n)
	}
	a.used[alias] = true
	a.byPath[pkg.Path()] = alias
	a.order = append(a.order, tplImport{Name: alias, Path: pkg.Path()})
	return alias
}

// render produces the generated file for pkg, or nil if there is nothing to generate.
func render(pkg *Package) ([]byte, error) {
	if len(pkg.Objects) == 0 && len(pkg.Registered) == 0 {
		return nil, nil
	}
	al := newAliases(pkg.Pkg.PkgPath)
	typeString := func(t types.Type) string { return types.TypeString(t, al.qualify) }

	// Unique component types in a deterministic order; allocating aliases in
	// import path order keeps clash suffixes (ext, ext2) stable.
	unique := map[string]*types.Named{}
	add := func(t *types.Named) { unique[types.TypeString(t, nil)] = t }
	for _, t := range pkg.Registered {
		add(t)
	}
	for _, obj := range pkg.Objects {
		for _, c := range obj.Components {
			add(c.Type)
			for _, e := range c.PtrEmbeds {
				add(e.Type)
			}
		}
	}
	keys := make([]string, 0, len(unique))
	for key := range unique {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	for _, key := range keys {
		typeString(unique[key])
	}

	file := tplFile{ComponentIDPrefix: componentIDPrefix, PackageName: pkg.Pkg.Name}

	componentTypes := map[string]bool{}
	for _, t := range pkg.Registered {
		componentTypes[types.TypeString(t, nil)] = true
	}
	for _, obj := range pkg.Objects {
		for _, c := range obj.Components {
			componentTypes[types.TypeString(c.Type, nil)] = true
		}
	}
	cidOwner := map[string]string{}
	for key := range componentTypes {
		name := typeString(unique[key])
		cid := componentIDPrefix + sanitizeIdentifier(name)
		if other, exists := cidOwner[cid]; exists {
			return nil, fmt.Errorf("%s: component types %s and %s produce the same name %s", pkg.Pkg.PkgPath, other, name, cid)
		}
		cidOwner[cid] = name
		info := pkg.Components[key]
		file.Components = append(file.Components, tplComp{
			Type: name, CID: cid, Component: true,
			Group: info.Group, CompName: info.Name, GoType: info.GoType,
			SchemaLit: schemaLiteral(info.Schema),
		})
	}
	sort.Slice(file.Components, func(i, j int) bool { return file.Components[i].Type < file.Components[j].Type })
	schemaVars := map[string]string{} // CID -> init variable
	for i := range file.Components {
		file.Components[i].SchemaVar = "s" + strconv.Itoa(i)
		schemaVars[file.Components[i].CID] = file.Components[i].SchemaVar
	}

	for _, obj := range pkg.Objects {
		file.Objects = append(file.Objects, renderObject(obj, pkg, typeString, schemaVars))
	}
	file.Imports = slices.Clone(al.order)
	sort.Slice(file.Imports, func(i, j int) bool { return file.Imports[i].Path < file.Imports[j].Path })

	tmpl, err := template.New("generator.go.tpl").Funcs(template.FuncMap{
		"sanitize": sanitizeIdentifier,
	}).ParseFS(templatesFS, "generator.go.tpl")
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	if err := tmpl.Execute(&b, file); err != nil {
		return nil, err
	}
	return b.Bytes(), nil
}

func renderObject(obj *Object, pkg *Package, typeString func(types.Type) string, schemaVars map[string]string) tplObject {
	out := tplObject{
		Name: obj.Name, GoType: obj.GoType(),
		Group: obj.Meta.Group, Class: obj.Meta.Class, Key: obj.Meta.Key(),
	}
	for _, c := range obj.Components {
		info := pkg.Components[types.TypeString(c.Type, nil)]
		cid := componentIDPrefix + sanitizeIdentifier(typeString(c.Type))
		out.Declared = append(out.Declared, tplComp{
			Name:      c.Name,
			Type:      typeString(c.Type),
			CID:       cid,
			Optional:  c.Optional,
			ByValue:   c.ByValue,
			SchemaVar: schemaVars[cid],
			Group:     info.Group,
			CompName:  info.Name,
		})
	}

	comps := slices.Clone(obj.Components)
	sort.Slice(comps, func(i, j int) bool { return comps[i].Name < comps[j].Name })

	seenEmbed := map[string]bool{}
	for _, c := range comps {
		typ := typeString(c.Type)
		tc := tplComp{
			Name:      c.Name,
			Path:      c.PathString(),
			Type:      typ,
			CID:       componentIDPrefix + sanitizeIdentifier(typ),
			Optional:  c.Optional,
			ByValue:   c.ByValue,
			Component: true,
		}
		if c.ByValue {
			tc.Deref = "*"
		}
		out.All = append(out.All, tc)
		if c.Optional {
			out.Optional = append(out.Optional, tc)
		} else {
			tc.Index = len(out.Required)
			tc.Var = "v" + strconv.Itoa(tc.Index)
			out.Required = append(out.Required, tc)
		}
		for _, e := range c.PtrEmbeds {
			if key := e.PathString(); !seenEmbed[key] {
				seenEmbed[key] = true
				out.PtrEmbeds = append(out.PtrEmbeds, tplEmbed{Path: key, Type: typeString(e.Type)})
			}
		}
	}
	// Embeds must be allocated outermost first.
	sort.SliceStable(out.PtrEmbeds, func(i, j int) bool {
		return strings.Count(out.PtrEmbeds[i].Path, ".") < strings.Count(out.PtrEmbeds[j].Path, ".")
	})

	out.Count = len(out.Required)
	out.Typed = out.Count >= 1 && out.Count <= maxTypedArity
	switch {
	case out.Count == 0:
		out.IterVar = "_"
	case out.Typed:
		out.IterVar = "comp"
	default:
		out.IterVar = "components"
	}

	var typeArgs, query, values, allCIDs []string
	for i := range out.Required {
		r := &out.Required[i]
		switch {
		case !out.Typed:
			r.Expr = fmt.Sprintf("components[%d].(*%s)", r.Index, r.Type)
		case out.Count == 1:
			r.Expr = out.IterVar
		default:
			r.Expr = fmt.Sprintf("%s.Comp%d", out.IterVar, r.Index+1)
		}
		typeArgs = append(typeArgs, r.Type)
		query = append(query, r.CID)
		values = append(values, r.Var)
	}
	out.TypeArgs = strings.Join(typeArgs, ", ")
	out.QueryArgs = strings.Join(query, ", ")
	out.ValueArgs = strings.Join(values, ", ")
	for _, c := range out.All {
		allCIDs = append(allCIDs, c.CID)
	}
	out.AllCIDArgs = strings.Join(allCIDs, ", ")
	return out
}

// sanitizeIdentifier turns a (qualified) type name into a CamelCase identifier part.
func sanitizeIdentifier(name string) string {
	parts := strings.FieldsFunc(name, func(r rune) bool { return !unicode.IsLetter(r) && !unicode.IsDigit(r) })
	if len(parts) == 0 {
		return "Field"
	}
	for i, part := range parts {
		parts[i] = strings.ToUpper(part[:1]) + part[1:]
	}
	return strings.Join(parts, "")
}

// godFile is the content of a package's GOD file.
type godFile struct {
	Version   int    `json:"version"`
	Generator string `json:"generator"`
	// Package is the import path of the package the file is generated
	// from. It lets write tell its own files in the specs folder from other
	// packages' (see writeSpecs).
	Package    string                `json:"package"`
	Components []god.ComponentSchema `json:"components"`
	Objects    []god.Schema          `json:"objects"`
}

// renderJSON produces the Game Object Definition of pkg, or nil if there is
// nothing to generate.
func renderJSON(pkg *Package) ([]byte, error) {
	if len(pkg.Objects) == 0 && len(pkg.Registered) == 0 {
		return nil, nil
	}
	file := godFile{
		Version: godVersion, Generator: godGenerator, Package: pkg.Pkg.PkgPath,
		Components: []god.ComponentSchema{}, Objects: []god.Schema{},
	}
	for _, info := range pkg.Components {
		file.Components = append(file.Components, god.ComponentSchema{
			Group: info.Group, Name: info.Name, Doc: info.Doc, GoType: info.GoType, Schema: info.Schema,
		})
	}
	slices.SortFunc(file.Components, func(a, b god.ComponentSchema) int { return strings.Compare(a.Key(), b.Key()) })
	for _, obj := range pkg.Objects {
		schema := god.Schema{SchemaMeta: obj.Meta, Doc: obj.Doc, GoType: obj.GoType(), Components: []god.Component{}}
		for _, c := range obj.Components {
			info := pkg.Components[types.TypeString(c.Type, nil)]
			schema.Components = append(schema.Components, god.Component{
				Group:    info.Group,
				Name:     info.Name,
				Field:    c.Name,
				Optional: c.Optional,
				Readonly: c.ByValue,

				Doc:         c.Doc,
				EmbeddedVia: c.Via,
			})
		}
		file.Objects = append(file.Objects, schema)
	}
	data, err := json.MarshalIndent(file, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(data, '\n'), nil
}

// schemaLiteral renders schema as a Go string literal holding its JSON, to be
// parsed by god.MustParseSchema. Documentation is left out: it belongs to
// the JSON file, not to the compiled program.
func schemaLiteral(schema *god.TypeSchema) string {
	data, err := json.Marshal(schema.WithoutDescriptions())
	if err != nil {
		panic(err) // TypeSchema always marshals
	}
	if strings.Contains(string(data), "`") {
		return strconv.Quote(string(data))
	}
	return "`" + string(data) + "`"
}
