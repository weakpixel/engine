// keyConst is one generated constant.
type keyConst struct {
	name, value string
}

// Keys writes a Go file of constants for the library's packages, files and clip
// tags, so game code names assets by identifier instead of by string. It is
// optional: a game that prefers strings never runs it. A library with errors
// is refused.
func Keys(opts KeysOptions, stdout io.Writer) error {
	root, err := resolveRoot(opts.Root)
	if err != nil {
		return err
	}
	pkg := opts.Pkg
	if pkg == "" {
		pkg = "assets"
	}
	fsys := os.DirFS(root)
	cat, findings, err := library.Scan(fsys)
	if err != nil {
		return err
	}
	if err := refuseErrors(findings); err != nil {
		return err
	}
	src, err := generateKeys(fsys, cat, pkg)
	if err != nil {
		return err
	}
	if opts.Out == "" || opts.Out == "-" {
		_, err = stdout.Write(src)
		return err
	}
	return os.WriteFile(opts.Out, src, 0o644)
}

// generateKeys returns the gofmt'ed source of the keys file:
//
//   - Package<Name> for every package ("world-1" -> PackageWorld1);
//   - Key<Path> for every file of a known kind, its path in CamelCase
//     without a ".json" extension ("global/hero/hero.anim.json" ->
//     KeyGlobalHeroHeroAnim, "temple/temple.png" -> KeyTempleTemplePng);
//   - Key<Path><Tag> for every tag of every animation definition, and of
//     every Aseprite export that is an entry of its package ("Idle L/R" ->
//     KeyGlobalHeroHeroAnimIdleLR = "global/hero/hero.anim.json#Idle L/R").
//
// Two paths that give the same identifier are an error, reported all at
// once.
func generateKeys(fsys fs.FS, cat *library.Catalog, pkg string) ([]byte, error) {
	var pkgs, files, clips []keyConst
	for _, g := range cat.Packages {
		pkgs = append(pkgs, keyConst{"Package" + ident(g.Name), g.Name})
	}
	entries := map[string]bool{}
	for _, g := range cat.Packages {
		for _, e := range g.Entries {
			entries[e] = true
		}
	}
	var errs []error
	err := fs.WalkDir(fsys, ".", func(p string, d fs.DirEntry, err error) error {
		if err != nil || !d.Type().IsRegular() || library.KindOf(p) == library.KindUnknown {
			return err
		}
		name := "Key" + ident(strings.TrimSuffix(p, ".json"))
		files = append(files, keyConst{name, p})
		tags, err := clipTags(fsys, p, entries[p])
		if err != nil {
			errs = append(errs, fmt.Errorf("%s: %w", p, err))
		}
		for _, tag := range tags {
			clips = append(clips, keyConst{name + ident(tag), p + "#" + tag})
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	seen := map[string]string{}
	for _, c := range slices.Concat(pkgs, files, clips) {
		if prev, dup := seen[c.name]; dup {
			errs = append(errs, fmt.Errorf("%q and %q both make the identifier %s; rename one", prev, c.value, c.name))
		}
		seen[c.name] = c.value
	}
	if len(errs) > 0 {
		return nil, errors.Join(errs...)
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by wpix assets keys; DO NOT EDIT.\n\npackage %s\n", pkg)
	writeConsts(&b, "Asset library packages (doc/guide/engine/asset-library.md).", pkgs)
	writeConsts(&b, "Asset keys, one per file of a known kind.", files)
	writeConsts(&b, "Clip keys, one per tag of each clip set.", clips)
	return format.Source(b.Bytes())
}

// clipTags returns the tag names of an animation definition, or of an
// Aseprite export that is a package entry; nil for other files.
func clipTags(fsys fs.FS, p string, entry bool) ([]string, error) {
	lower := strings.ToLower(p)
	sheetPath := ""
	switch {
	case strings.HasSuffix(lower, ".anim.json"):
		data, err := fs.ReadFile(fsys, p)
		if err != nil {
			return nil, err
		}
		def, err := animfile.Decode(data)
		if err != nil {
			return nil, err
		}
		sheetPath = path.Join(path.Dir(p), def.Sheet)
	case strings.HasSuffix(lower, ".aseprite.json") && entry:
		sheetPath = p
	default:
		return nil, nil
	}
	data, err := fs.ReadFile(fsys, sheetPath)
	if err != nil {
		return nil, err
	}
	sheet, err := animfile.DecodeSheet(data)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", sheetPath, err)
	}
	var tags []string
	for _, t := range sheet.Tags {
		tags = append(tags, t.Name)
	}
	return tags, nil
}

func writeConsts(b *bytes.Buffer, doc string, consts []keyConst) {
	if len(consts) == 0 {
		return
	}
	fmt.Fprintf(b, "\n// %s\nconst (\n", doc)
	for _, c := range consts {
		fmt.Fprintf(b, "\t%s = %q\n", c.name, c.value)
	}
	b.WriteString(")\n")
}

// ident turns text into the CamelCase words of its letters and digits:
// "world-1" -> "World1", "Idle L/R" -> "IdleLR".
func ident(s string) string {
	var b strings.Builder
	upper := true
	for _, r := range s {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			upper = true
			continue
		}
		if upper {
			r = unicode.ToUpper(r)
			upper = false
		}
		b.WriteRune(r)
	}
	return b.String()
}
