func runEmbed(opts EmbedOptions) (int, string, string) {
	return result(func(w io.Writer) error { return Embed(opts, w) })
}

// withIgnores is goodLib with work files and the ignore files that keep
// them out.
func withIgnores() map[string]string {
	files := maps.Clone(goodLib)
	files[".assetignore"] = "*.psd\n/drafts/\n"
	files["global/hero/hero.psd"] = "psd"
	files["drafts/draft.png"] = "png"
	files["forest/.assetignore"] = "raw/\n"
	files["forest/raw/sketch.png"] = "png"
	return files
}

func TestEmbedPatterns(t *testing.T) {
	tests := []struct {
		name  string
		files map[string]string
		want  []string
	}{
		{"no ignore file embeds the folder", goodLib, []string{"assets"}},
		{"ignored files listed around", withIgnores(), []string{
			"assets/forest/forest.tmj",
			"assets/global/hero/hero.anim.json",
			"assets/global/hero/hero.aseprite.json",
			"assets/global/hero/hero.png",
			"assets/readme.txt",
			"assets/trees",
		}},
		{"underscore file below the top is a library file", map[string]string{
			"global/a.wav":       "wav",
			"global/_wip/b.wav":  "wav",
			"forest/c.wav":       "wav",
			"forest/d/e.wav":     "wav",
			"_sources/x.psd":     "reserved",
			"packs/old.zip":      "reserved",
			"forest/d/.keep.wav": "dot",
		}, []string{
			"assets/forest/c.wav",
			"assets/forest/d/.keep.wav",
			"assets/forest/d/e.wav",
			"assets/global/_wip", // named, so go:embed walks it
			"assets/global/a.wav",
		}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			root := writeFiles(t, tt.files)
			got, err := embedPatterns(os.DirFS(root), "assets")
			if err != nil {
				t.Fatal(err)
			}
			if !slices.Equal(got, tt.want) {
				t.Fatalf("patterns\n%s\nwant\n%s", strings.Join(got, "\n"), strings.Join(tt.want, "\n"))
			}
		})
	}
}

func TestEmbedRefuses(t *testing.T) {
	root := writeFiles(t, map[string]string{"global/a[1].wav": "wav"})
	if _, err := embedPatterns(os.DirFS(root), "assets"); err == nil || !strings.Contains(err.Error(), "global/a[1].wav: the name has a character go:embed cannot match") {
		t.Fatalf("meta character: %v", err)
	}
	if _, err := embedPatterns(os.DirFS(root), "../assets"); err == nil || !strings.Contains(err.Error(), "must be a folder below the package folder") {
		t.Fatalf("root outside: %v", err)
	}
	if code, _, errOut := runEmbed(EmbedOptions{Root: writeFiles(t, badLib)}); code != exitError || !strings.Contains(errOut, "the library has errors") {
		t.Fatalf("bad library: code %d %s", code, errOut)
	}
}

func TestEmbedOutput(t *testing.T) {
	pkgDir := t.TempDir()
	root := filepath.Join(pkgDir, "assets")
	if err := os.CopyFS(root, os.DirFS(writeFiles(t, withIgnores()))); err != nil {
		t.Fatal(err)
	}
	t.Chdir(pkgDir)
	code, out, errOut := runEmbed(EmbedOptions{Root: "assets", Tags: "!editor", Var: "lib"})
	if code != exitOK {
		t.Fatalf("code %d: %s", code, errOut)
	}
	for _, want := range []string{
		"// Code generated by wpix assets embed; DO NOT EDIT.\n\n//go:build !editor\n\npackage main\n",
		"//go:embed assets/trees\nvar lib embed.FS\n",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("output lacks %q:\n%s", want, out)
		}
	}
	_, again, _ := runEmbed(EmbedOptions{Root: "assets", Tags: "!editor", Var: "lib"})
	if again != out {
		t.Error("output is not deterministic")
	}
}

// TestEmbedCompiles builds a program with the generated file and checks
// that it embeds exactly the library's files.
func TestEmbedCompiles(t *testing.T) {
	if _, err := exec.LookPath("go"); err != nil {
		t.Skip("go not found")
	}
	pkgDir := t.TempDir()
	files := withIgnores()
	files["global/_wip/b.wav"] = "wav"
	if err := os.CopyFS(filepath.Join(pkgDir, "assets"), os.DirFS(writeFiles(t, files))); err != nil {
		t.Fatal(err)
	}
	t.Chdir(pkgDir)
	if code, _, errOut := runEmbed(EmbedOptions{Root: "assets", Out: "zz__gen.assets_embed.go"}); code != exitOK {
		t.Fatalf("embed: %s", errOut)
	}
	main := `package main

import (
	"fmt"
	"io/fs"
)

func main() {
	fs.WalkDir(assets, ".", func(p string, d fs.DirEntry, err error) error {
		if err == nil && !d.IsDir() {
			fmt.Println(p)
		}
		return err
	})
}
`
	if err := os.WriteFile("main.go", []byte(main), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile("go.mod", []byte("module embedtest\n\ngo 1.27\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	cmd := exec.Command("go", "run", ".")
	cmd.Env = append(os.Environ(), "GOFLAGS=-mod=mod", "GOWORK=off")
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("go run: %v\n%s", err, out)
	}
	got := strings.Fields(string(out))
	want := []string{
		"assets/forest/forest.tmj",
		"assets/global/_wip/b.wav",
		"assets/global/hero/hero.anim.json",
		"assets/global/hero/hero.aseprite.json",
		"assets/global/hero/hero.png",
		"assets/readme.txt",
		"assets/trees/trees.png",
		"assets/trees/trees.tsj",
	}
	if !slices.Equal(got, want) {
		t.Fatalf("embedded\n%s\nwant\n%s", strings.Join(got, "\n"), strings.Join(want, "\n"))
	}
}

func TestCheckCountsIgnored(t *testing.T) {
	code, out, _ := runCheck(CheckOptions{Root: writeFiles(t, withIgnores())})
	if code != exitOK || !strings.Contains(out, "3 files ignored by .assetignore (wpix assets ls --ignored)\n") {
		t.Fatalf("code %d\n%s", code, out)
	}
}

